"""Crowd-aware itinerary planner (deterministic, rule-based; no LLM).

For each day it repeatedly picks the next attraction that best balances interest match, predicted crowd at
the arrival time, travel time from the previous stop and (when live weather is available) rain at an
uncovered site, while respecting opening hours. Travel times are straight-line ESTIMATES.
"""
from __future__ import annotations

import datetime as dt
import math

from ..models import Attraction, Destination
from . import crowd, runtime
from .recommender import haversine_km

PACE_STOPS = {"relaxed": 3, "normal": 4, "packed": 5}
DAY_START = {"relaxed": 9 * 60 + 30, "normal": 9 * 60, "packed": 8 * 60}
DAY_END = 19 * 60 + 30
ROAD_FACTOR = 1.4
SPEED_KMH = 25
MAX_WAIT = 90
DISCLAIMER = ("Generated by TripNest's rule-based planner using demonstration-trained crowd forecasts. Travel times "
              "are straight-line estimates; opening hours and fees are indicative. Check locally before you go.")


def hm(m: int) -> str:
    m = int(m)
    return f"{m // 60:02d}:{m % 60:02d}"


def travel_min(a_lat, a_lon, b_lat, b_lon) -> int:
    km = haversine_km(a_lat, a_lon, b_lat, b_lon) * ROAD_FACTOR
    return max(10, int(math.ceil(km / SPEED_KMH * 60 / 5) * 5))


def suitable(a: Attraction, group: str) -> bool:
    if group == "family" and not a.family_friendly:
        return False
    if group == "elders" and not a.elder_friendly:
        return False
    return True


def interest(a: Attraction, interests: list[str]) -> float:
    if not interests:
        return 0.5
    tags = set(a.tags or []) | {a.category}
    return sum(i in tags for i in interests) / len(interests)


def _forecast_map(a: Attraction, d: dt.date) -> dict[int, dict]:
    return {h["hour"]: h for h in runtime.day_forecast(runtime.spec(a), d)}


def _predicted(fc: dict[int, dict], minute: int, a: Attraction) -> dict:
    h = fc.get(minute // 60)
    if not h:
        return {"util": 0.0, "level": "Low", "visitors": 0}
    return {"util": h["util"], "level": h["level"], "visitors": h["visitors"]}


def _stop(a: Attraction, start: int, travel: int | None, fc: dict, note: str) -> dict:
    p = _predicted(fc, start, a)
    tip = None
    if p["level"] in ("High", "At Capacity"):
        quiet = min((h for h in fc.values() if a.open_hour <= h["hour"] and h["hour"] * 60 + a.visit_min <= a.close_hour * 60),
                    key=lambda h: h["util"], default=None)
        if quiet and quiet["hour"] != start // 60:
            tip = f"Quieter around {hm(quiet['hour'] * 60)} ({quiet['level']})."
    return {"slug": a.slug, "name": a.name, "category": a.category, "lat": a.lat, "lon": a.lon,
            "start": hm(start), "end": hm(start + a.visit_min), "visit_min": a.visit_min,
            "open_hour": a.open_hour, "close_hour": a.close_hour, "fee": a.fee, "covered": a.covered,
            "travel_min": travel, "travel_note": note, "predicted": p, "tip": tip}


def plan_day(dest: Destination, day: dt.date, used: set[str], interests: list[str], group: str, pace: str,
             start_min: int | None = None, max_stops: int | None = None, rain: dict | None = None) -> dict:
    t = start_min if start_min is not None else DAY_START[pace]
    n = max_stops if max_stops is not None else PACE_STOPS[pace]
    cands = [a for a in dest.attractions if a.slug not in used and suitable(a, group)]
    fcs = {a.slug: _forecast_map(a, day) for a in cands}
    stops, breaks, prev, lunch = [], [], None, False
    while len(stops) < n and t < DAY_END and cands:
        best = None
        for a in cands:
            travel = travel_min(prev.lat, prev.lon, a.lat, a.lon) if prev else 0
            arrive = t + travel
            start = max(arrive, a.open_hour * 60)
            end = start + a.visit_min
            if end > a.close_hour * 60 or start - arrive > MAX_WAIT or end > DAY_END + 60:
                continue
            p = _predicted(fcs[a.slug], start, a)
            rain_p = (rain or {}).get((day, start // 60), 0.0)
            score = (2.0 * interest(a, interests) + 0.25 * min(a.popularity, 1.3)
                     - 1.0 * p["util"] - (0.6 if p["util"] >= 0.9 else 0)
                     - travel / 120 - (start - arrive) / 120
                     - (0.6 * rain_p if not a.covered else 0))
            if best is None or score > best[0]:
                best = (score, a, travel, start)
        if best is None:
            break
        _, a, travel, start = best
        if prev:
            note = f"~{travel} min from {prev.name} (straight-line estimate)"
        else:
            note = "Start of the day"
        stops.append(_stop(a, start, travel if prev else None, fcs[a.slug], note))
        used.add(a.slug)
        cands.remove(a)
        prev, t = a, start + a.visit_min
        if not lunch and t >= 12 * 60 + 30:
            breaks.append({"label": "Lunch break", "start": hm(t), "end": hm(t + 60)})
            t += 60
            lunch = True
    return {"stops": stops, "breaks": breaks}


def allocate_days(dests: list[Destination], days: int) -> list[Destination]:
    base, extra = divmod(days, len(dests))
    order = []
    for i, d in enumerate(dests):
        order += [d] * (base + (1 if i < extra else 0))
    return order or dests[:1]


def estimate_cost(plan_days: list[dict], dests_by_slug: dict) -> int:
    total = 0
    for d in plan_days:
        total += dests_by_slug[d["destination"]["slug"]].daily_cost
        total += sum(s["fee"] for s in d["stops"])
    return total


def generate(dests: list[Destination], start_date: dt.date, days: int, interests: list[str], group: str,
             pace: str, weather: dict | None = None) -> dict:
    order = allocate_days(dests, days)
    used: set[str] = set()
    out_days, warnings = [], []
    for i, d in enumerate(order):
        day = start_date + dt.timedelta(days=i)
        travel_note, start_min, max_stops = None, None, None
        if i > 0 and order[i - 1].id != d.id:
            prev = order[i - 1]
            km = haversine_km(prev.lat, prev.lon, d.lat, d.lon)
            hrs = max(1, round(km * ROAD_FACTOR / 50))
            travel_note = (f"Travel from {prev.name} to {d.name}: about {int(km)} km in a straight line, "
                           f"roughly {hrs} h by road (estimate). Check trains and flights.")
            start_min = min(DAY_END - 180, DAY_START[pace] + hrs * 60)
            max_stops = max(1, PACE_STOPS[pace] - 2)
        rain = (weather or {}).get(d.slug)
        pd_ = plan_day(d, day, used, interests, group, pace, start_min, max_stops, rain)
        if not pd_["stops"]:
            warnings.append(f"Day {i + 1}: no further catalogued attractions fit in {d.name}; keep it as free time.")
        busy = [s["name"] for s in pd_["stops"] if s["predicted"]["level"] == "At Capacity"]
        if busy:
            warnings.append(f"Day {i + 1}: {', '.join(busy)} may be at capacity; see the quieter-time tips.")
        out_days.append({"day": i + 1, "date": day.isoformat(),
                         "destination": {"slug": d.slug, "name": d.name, "lat": d.lat, "lon": d.lon},
                         "travel_note": travel_note, **pd_})
    by_slug = {d.slug: d for d in dests}
    return {"days": out_days, "warnings": warnings,
            "estimated_cost_inr": estimate_cost(out_days, by_slug),
            "cost_note": "Indicative per-person estimate: destination daily cost plus entry fees.",
            "weather_used": bool(weather and any(weather.values())),
            "generated_by": "TripNest rule-based planner + crowd forecasting model",
            "disclaimer": DISCLAIMER, "provenance": runtime.provenance()}


def retime(plan: dict, edits: list[list[Attraction]], pace: str) -> dict:
    """Recompute times after a user reorders/removes stops. Keeps dates and destinations."""
    new_days = []
    for i, attrs in enumerate(edits):
        old = plan["days"][i]
        day = dt.date.fromisoformat(old["date"])
        t = DAY_START.get(pace, 9 * 60)
        if old.get("travel_note"):
            t = max(t, 12 * 60)
        stops, breaks, prev, lunch = [], [], None, False
        for a in attrs:
            fc = _forecast_map(a, day)
            travel = travel_min(prev.lat, prev.lon, a.lat, a.lon) if prev else None
            start = max(t + (travel or 0), a.open_hour * 60)
            s = _stop(a, start, travel, fc, f"~{travel} min from {prev.name} (straight-line estimate)" if prev
                      else "Start of the day")
            if start + a.visit_min > a.close_hour * 60:
                s["warning"] = "Closes before this visit would end; consider moving it earlier."
            stops.append(s)
            prev, t = a, start + a.visit_min
            if not lunch and t >= 12 * 60 + 30:
                breaks.append({"label": "Lunch break", "start": hm(t), "end": hm(t + 60)})
                t += 60
                lunch = True
        new_days.append({**old, "stops": stops, "breaks": breaks})
    return {**plan, "days": new_days, "edited": True}


__all__ = ["generate", "retime", "crowd"]
